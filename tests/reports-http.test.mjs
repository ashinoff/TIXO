import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createServer } from 'node:http';
import next from 'next';
import pg from 'pg';
import ExcelJS from 'exceljs';
const databaseUrl = process.env.TEST_DATABASE_URL;
test('trade reports: admin-only snapshots, expense versions, numeric Excel, valid dates and unchanged operational data', { skip: !databaseUrl }, async t => {
  const schema = `tixo_reports_${randomUUID().replaceAll('-', '')}`;
  const url = new URL(databaseUrl); url.searchParams.set('options', `-c search_path=${schema}`);
  const pool = new pg.Pool({ connectionString: url.toString() }); await pool.query(`CREATE SCHEMA ${schema}`);
  process.env.DATABASE_URL = url.toString(); process.env.PGSSL = 'false'; process.env.ADMIN_PASSWORD = randomUUID(); process.env.SESSION_SECRET = randomUUID();
  globalThis.tihoPool = pool; globalThis.tihoSchemaReady = undefined;
  const app = next({ dev: false, dir: process.cwd() }); await app.prepare();
  const server = createServer(app.getRequestHandler()); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await app.close(); await pool.query(`DROP SCHEMA ${schema} CASCADE`); await pool.end(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (path, options = {}) => fetch(base + path, options);
  const json = body => ({ headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
  assert.equal((await call('/api/admin/reports')).status, 401);
  assert.equal((await call('/api/admin/reports/export')).status, 401);
  assert.equal((await call('/api/admin/reports', { method: 'POST', ...json({ action: 'expense' }) })).status, 401);
  const login = await call('/api/admin/login', { method: 'POST', ...json({ password: process.env.ADMIN_PASSWORD }) });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const admin = (path, options = {}) => call(path, { ...options, headers: { ...options.headers, cookie } });
  let res = await admin('/api/admin/reports'); assert.equal(res.status, 200); assert.equal(res.headers.get('cache-control'), 'no-store');
  const initial = await res.json(); assert.ok(initial.inventory.length); assert.equal(initial.summary.expenseTotal, 0);
  const product = initial.inventory[0];
  const baseline = (await pool.query('SELECT id,price,stock,updated_at FROM products ORDER BY id')).rows;
  const wax = (await pool.query("SELECT id FROM costing_materials WHERE name='Воск'")).rows[0].id;
  res = await admin('/api/admin/costing', { method: 'POST', ...json({ action: 'recipe', name: 'Проверка остатков', product_ids: [product.id], items: { [wax]: 100 }, markup_pct: 100, sale_price: null }) }); assert.equal(res.status, 200);
  let report = await (await admin('/api/admin/reports')).json(); assert.equal(report.inventory.find(p => p.id === product.id).unitCost, 65);
  const post = body => admin('/api/admin/reports', { method: 'POST', ...json(body) });
  const expense = { action: 'expense', date: '2026-11-11', category: 'Материалы', description: '=1+1', amount: 1234.56 };
  assert.equal((await post(expense)).status, 200);
  report = await (await admin('/api/admin/reports?from=2026-11-01&to=2026-11-30')).json();
  assert.equal(report.summary.expenseTotal, 1234.56); const saved = report.expenses[0]; assert.equal(typeof saved.id, 'number');
  for (const date of ['2026-02-30', '2026-13-01', 'not-a-date', '', '1999-01-01']) assert.equal((await post({ ...expense, date })).status, 400, date);
  for (const amount of [null, true, '', 0, -2, 1.234, 100000001]) assert.equal((await post({ ...expense, amount })).status, 400, String(amount));
  assert.equal((await admin('/api/admin/reports?from=2026-12-01&to=2026-11-01')).status, 400);
  assert.equal((await admin('/api/admin/reports?from=2026-13-01')).status, 400);
  assert.equal((await admin('/api/admin/reports/export?kind=unknown')).status, 400);
  assert.equal((await admin('/api/admin/reports/export?from=broken')).status, 400);
  res = await admin('/api/admin/reports/export?kind=all&from=2026-11-01&to=2026-11-30'); assert.equal(res.status, 200);
  assert.match(res.headers.get('content-type'), /spreadsheetml/); assert.equal(res.headers.get('cache-control'), 'no-store');
  const book = new ExcelJS.Workbook(); await book.xlsx.load(Buffer.from(await res.arrayBuffer()));
  assert.equal(book.getWorksheet('Расходы').getCell('D2').value, '=1+1'); assert.equal(book.getWorksheet('Расходы').getCell('E2').value, 1234.56);
  assert.equal((await post({ ...expense, id: saved.id, version: saved.version, amount: 1500 })).status, 200);
  assert.equal((await post({ ...expense, id: saved.id, version: saved.version, amount: 1600 })).status, 409);
  assert.equal((await post({ action: 'remove-expense', id: saved.id, version: saved.version })).status, 409);
  assert.equal((await post({ action: 'remove-expense', id: saved.id, version: saved.version + 1 })).status, 200);
  report = await (await admin('/api/admin/reports')).json(); assert.equal(report.summary.expenseTotal, 0);
  assert.equal((await pool.query('SELECT archived FROM costing_expenses WHERE id=$1', [saved.id])).rows[0].archived, true, 'Removal is archival, preserving the record');
  assert.deepEqual((await pool.query('SELECT id,price,stock,updated_at FROM products ORDER BY id')).rows, baseline, 'Reports, exports and expenses never mutate products or stock');
  assert.equal(Number((await pool.query('SELECT count(*) FROM orders')).rows[0].count), 0, 'Reports never create customer orders');
});
