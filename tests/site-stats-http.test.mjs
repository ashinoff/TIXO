import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createServer } from 'node:http';
import next from 'next';
import pg from 'pg';

const databaseUrl = process.env.TEST_DATABASE_URL;
test('anonymous page counts: no visitor records, strict input, concurrency, Moscow periods and admin-only reports', { skip: !databaseUrl }, async t => {
  const schema = `tixo_stats_${randomUUID().replaceAll('-', '')}`;
  const url = new URL(databaseUrl); url.searchParams.set('options', `-c search_path=${schema}`);
  const pool = new pg.Pool({ connectionString: url.toString() }); await pool.query(`CREATE SCHEMA ${schema}`);
  process.env.DATABASE_URL = url.toString(); process.env.PGSSL = 'false'; process.env.ADMIN_PASSWORD = randomUUID(); process.env.SESSION_SECRET = randomUUID();
  globalThis.tihoPool = pool; globalThis.tihoSchemaReady = undefined; globalThis.tihoStatsReady = undefined;
  const app = next({ dev: false, dir: process.cwd() }); await app.prepare();
  const server = createServer(app.getRequestHandler()); await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await app.close(); await pool.query(`DROP SCHEMA ${schema} CASCADE`); await pool.end(); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = (path, options = {}) => fetch(base + path, options);
  const json = body => ({ headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
  const post = (body = { path: '/' }, headers = {}) => call('/api/stats/pageview', { method: 'POST', body: JSON.stringify(body), headers: { origin: base, 'content-type': 'application/json', 'user-agent': 'Mozilla/5.0', ...headers } });
  assert.equal((await call('/api/admin/stats')).status, 401);
  const login = await call('/api/admin/login', { method: 'POST', ...json({ password: process.env.ADMIN_PASSWORD }) }); assert.equal(login.status, 200);
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const admin = path => call(path, { headers: { cookie } });
  let res = await admin('/api/admin/stats'); assert.equal(res.status, 200); assert.equal(res.headers.get('cache-control'), 'no-store');
  let report = await res.json();
  assert.deepEqual(report.summary, { today: 0, week: 0, month: 0, total: 0 });
  assert.equal(report.daily.length, 30); assert.ok(report.daily.every(row => row.views === 0)); assert.deepEqual(report.pages, []);
  assert.equal((await call('/api/stats/pageview', { method: 'POST', ...json({ path: '/' }) })).status, 403);
  for (const origin of ['https://other.example', 'null', 'malformed']) assert.equal((await post({ path: '/' }, { origin })).status, 403);
  assert.equal((await post({ path: '/' }, { 'sec-fetch-site': 'cross-site' })).status, 403);
  assert.equal((await post({ path: '/' }, { 'content-type': 'text/plain' })).status, 415);
  for (const body of [{ path: '/admin' }, { path: '/?email=private' }, { path: '/', visitor: 'private' }, { path: '/privacy#section-1' }, null, [], { path: 1 }]) assert.equal((await post(body)).status, 400);
  assert.equal((await call('/api/stats/pageview', { method: 'POST', headers: { origin: base, 'content-type': 'application/json' }, body: '{' })).status, 400);
  assert.equal((await post({ path: '/'.repeat(129) })).status, 413);
  const responses = await Promise.all(Array.from({ length: 20 }, () => post()));
  for (const response of responses) { assert.equal(response.status, 204); assert.equal(response.headers.get('set-cookie'), null); assert.equal(response.headers.get('cache-control'), 'no-store'); }
  for (const path of ['/privacy', '/consent']) assert.equal((await post({ path })).status, 204);
  for (const agent of ['Googlebot', 'HeadlessChrome', 'facebookexternalhit']) assert.equal((await post({ path: '/' }, { 'user-agent': agent })).status, 204);
  report = await (await admin('/api/admin/stats')).json();
  assert.deepEqual(report.summary, { today: 22, week: 22, month: 22, total: 22 }, 'Concurrent updates must not lose views; known bots must not add views');
  const columns = await pool.query("SELECT column_name FROM information_schema.columns WHERE table_schema=$1 AND table_name='site_page_counts' ORDER BY ordinal_position", [schema]);
  assert.deepEqual(columns.rows.map(row => row.column_name), ['day', 'path', 'views'], 'No events, IPs, identities, user agents or per-visitor records');
  const today = (await pool.query("SELECT (CURRENT_TIMESTAMP AT TIME ZONE 'Europe/Moscow')::date::text AS day")).rows[0].day;
  assert.equal(report.to, today); assert.equal(report.daily.at(-1).date, today);
  await pool.query(`INSERT INTO site_page_counts(day,path,views) SELECT (CURRENT_TIMESTAMP AT TIME ZONE 'Europe/Moscow')::date-d, p, n FROM (VALUES (6,'/',7),(7,'/',11),(29,'/privacy',13),(30,'/',17),(100,'/',19),(-1,'/',5)) AS sample(d,p,n)`);
  report = await (await admin('/api/admin/stats?days=7')).json();
  assert.deepEqual(report.summary, { today: 22, week: 29, month: 53, total: 89 });
  assert.equal(report.daily.length, 7); assert.equal(report.daily[0].views, 7); assert.equal(report.daily[1].views, 0);
  assert.equal(report.pages.find(row => row.path === '/').views, 27);
  report = await (await admin('/api/admin/stats?days=90')).json(); assert.equal(report.daily.length, 90); assert.equal(report.daily.reduce((sum, row) => sum + row.views, 0), 70);
  for (const days of ['', '1', '365', '-7', '7.0', 'invalid']) assert.equal((await admin(`/api/admin/stats?days=${days}`)).status, 400);
  // Initialise the shop independently, then confirm statistics do not touch operational data.
  assert.equal((await call('/api/products')).status, 200);
  const products = (await pool.query('SELECT id,price,stock,updated_at FROM products ORDER BY id')).rows;
  const orders = (await pool.query('SELECT count(*) FROM orders')).rows;
  await post(); await admin('/api/admin/stats');
  assert.deepEqual((await pool.query('SELECT id,price,stock,updated_at FROM products ORDER BY id')).rows, products);
  assert.deepEqual((await pool.query('SELECT count(*) FROM orders')).rows, orders);
});
